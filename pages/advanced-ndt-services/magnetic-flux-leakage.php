                    <h2>What is Magnetic Flux Leakage Tank Floor Inspection?</h2>
                    <p class="lead">Magnetic Flux Leakage (MFL) is a highly efficient electromagnetic inspection technique that detects corrosion, pitting, and metal loss in atmospheric storage tank bottom plates by measuring distortions in an induced magnetic field caused by wall thickness variations and defects.</p>
                    <p>MFL tank floor scanners consist of a mobile platform equipped with powerful permanent magnets or electromagnets that magnetize the steel floor plate to near saturation. When the magnetic field encounters a defect such as corrosion pit, uniform thinning, or crack, flux lines "leak" from the steel surface. An array of Hall-effect sensors or magnetic flux detectors positioned between the magnet poles measures these flux leakage patterns in real-time as the scanner traverses the tank floor.</p>
                    <p>The technology simultaneously detects topside corrosion (internal tank surface degradation from stored product, water bottoms, microbiological activity) and underside corrosion (external soil-side corrosion from groundwater, foundation settlement, poor drainage). Signal amplitude correlates to defect depth, enabling accurate remaining wall thickness calculation and metal loss quantification per API 653 Annex G criteria.</p>

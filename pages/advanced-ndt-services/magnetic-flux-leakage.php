                <div class="faq-item">
                    <div class="faq-question">
                        <h3>How accurate is MFL compared to ultrasonic thickness (UT) testing?</h3> <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-answer">
                        <p>MFL provides ±0.1mm (±0.004") or ±3% thickness measurement accuracy when properly calibrated per API 653 Annex G—comparable to UT gauge accuracy. However, MFL scans 100% of floor area versus UT spot checks covering only 5-10% in a grid pattern. MFL identifies all corrosion zones for targeted UT verification, combining MFL's comprehensive coverage with UT's point accuracy. API 653 Annex G.3.2 requires minimum 10-20 UT verification measurements to validate MFL results, typically showing excellent correlation (±0.1-0.2mm).</p>
                    </div>
                </div>
                <div class="faq-item">
                    <div class="faq-question">
                        <h3>Can MFL detect underside (soil-side) corrosion?</h3> <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-answer">
                        <p>Yes, this is a major advantage of MFL. The magnetic field penetrates the full plate thickness, so flux leakage occurs from defects on either the topside (internal/product-side) or underside (external/soil-side) of the floor plate. MFL cannot definitively determine which surface contains the corrosion, but it accurately measures total remaining wall thickness regardless of defect location. This is critical because underside corrosion from groundwater infiltration, cathodic protection failure, or poor foundation drainage is completely invisible during visual internal inspection but can cause catastrophic tank failure.</p>
                    </div>
                </div>
                <div class="faq-item">
                    <div class="faq-question">
                        <h3>What tank conditions or factors can interfere with MFL inspection?</h3> <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-answer">
                        <p>MFL performance is affected by: (1) Heavy sludge/sediment >25mm thick—obscures floor surface and reduces magnetic coupling (sweep cleaning usually sufficient); (2) Thick internal coatings >2mm—attenuate magnetic field (most tanks have bare steel or thin coatings); (3) Non-magnetic floor plates (stainless steel, aluminum, FRP)—MFL only works on ferromagnetic materials; (4) Severe floor unevenness/buckling >50mm—scanner may lose contact; (5) Inaccessible areas under column supports—require UT spot checks. Despite these limitations, MFL successfully inspects 95-98% of typical tank floor area.</p>

                <div class="faq-item">
                    <div class="faq-question">
                        <h3>What is the difference between inspection and thorough examination?</h3>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-answer">
                        <p><strong>Inspection</strong> typically refers to pre-use checks and routine visual inspections performed by operators or maintenance personnel. <strong>Thorough examination</strong> is a more detailed statutory examination carried out by a competent person at specified intervals. It includes functional testing, NDT where appropriate, and formal documentation. Thorough examination is a legal requirement in most jurisdictions and must be performed by someone with appropriate training, knowledge, and experience (a "competent person").</p>
                    </div>
                </div>


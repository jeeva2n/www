                    </div>
                    <div class="faq-answer">
                        <p>Inspection frequency depends on equipment type, usage, and regulatory requirements. Under LOLER, thorough examination is typically required every 6 months for equipment used to lift people and every 12 months for other lifting equipment. However, more frequent inspections may be required based on usage intensity, environmental conditions, or after incidents. Our competent persons assess each item and recommend appropriate intervals. We also provide scheduled inspection programs with automatic reminders to ensure continuous compliance.</p>
                    </div>
